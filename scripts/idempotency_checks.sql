
-- 1. Check duplicate transaction IDs in Silver
SELECT
    EVENT_ID,
    COUNT(*) AS RECORD_COUNT
FROM SMART_DATA_QUALITY_DB.SILVER.VALID_TRANSACTIONS
GROUP BY EVENT_ID
HAVING COUNT(*) > 1;


-- 2. Check duplicate transaction IDs in Gold
SELECT
    EVENT_ID,
    COUNT(*) AS RECORD_COUNT
FROM SMART_DATA_QUALITY_DB.GOLD.FACT_TRANSACTIONS
GROUP BY EVENT_ID
HAVING COUNT(*) > 1;


-- 3. Check duplicate quarantine IDs
SELECT
    QUARANTINE_ID,
    COUNT(*) AS RECORD_COUNT
FROM SMART_DATA_QUALITY_DB.SILVER.QUARANTINE_RECORDS
GROUP BY QUARANTINE_ID
HAVING COUNT(*) > 1;


-- 4. Review pending and replayed records
SELECT
    STATUS,
    COUNT(*) AS RECORD_COUNT
FROM SMART_DATA_QUALITY_DB.SILVER.QUARANTINE_RECORDS
GROUP BY STATUS;


-- 5. Review replay attempts
SELECT
    QUARANTINE_ID,
    EVENT_ID,
    REPLAY_STATUS,
    COUNT(*) AS ATTEMPT_COUNT
FROM SMART_DATA_QUALITY_DB.AUDIT.REPLAY_HISTORY
GROUP BY
    QUARANTINE_ID,
    EVENT_ID,
    REPLAY_STATUS
ORDER BY EVENT_ID;
