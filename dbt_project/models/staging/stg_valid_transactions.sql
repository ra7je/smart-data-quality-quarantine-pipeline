
SELECT
    EVENT_ID,
    CUSTOMER_ID,
    UPPER(TRIM(EVENT_TYPE)) AS EVENT_TYPE,
    CAST(AMOUNT AS NUMBER(18,2)) AS AMOUNT,
    CAST(EVENT_TIMESTAMP AS TIMESTAMP_NTZ) AS EVENT_TIMESTAMP,
    CAST(EVENT_TIMESTAMP AS DATE) AS TRANSACTION_DATE,
    SOURCE_FILE,
    RUN_ID
FROM {{ source('smart_data_quality_silver', 'valid_transactions') }}
WHERE EVENT_ID IS NOT NULL
  AND CUSTOMER_ID IS NOT NULL
  AND AMOUNT > 0
