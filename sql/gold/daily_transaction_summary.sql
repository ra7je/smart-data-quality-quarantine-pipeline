
CREATE TABLE IF NOT EXISTS SMART_DATA_QUALITY_DB.GOLD.DAILY_TRANSACTION_SUMMARY (
    TRANSACTION_DATE DATE,
    EVENT_TYPE VARCHAR(20),
    TRANSACTION_COUNT NUMBER,
    TOTAL_AMOUNT NUMBER(18,2),
    AVERAGE_AMOUNT NUMBER(18,2),
    LAST_UPDATED_AT TIMESTAMP_NTZ
);


MERGE INTO SMART_DATA_QUALITY_DB.GOLD.DAILY_TRANSACTION_SUMMARY T
USING (
    SELECT
        CAST(EVENT_TIMESTAMP AS DATE) AS TRANSACTION_DATE,
        EVENT_TYPE,
        COUNT(*) AS TRANSACTION_COUNT,
        SUM(AMOUNT) AS TOTAL_AMOUNT,
        AVG(AMOUNT) AS AVERAGE_AMOUNT
    FROM SMART_DATA_QUALITY_DB.GOLD.FACT_TRANSACTIONS
    GROUP BY
        CAST(EVENT_TIMESTAMP AS DATE),
        EVENT_TYPE
) S
ON T.TRANSACTION_DATE = S.TRANSACTION_DATE
AND T.EVENT_TYPE = S.EVENT_TYPE

WHEN MATCHED THEN UPDATE SET
    T.TRANSACTION_COUNT = S.TRANSACTION_COUNT,
    T.TOTAL_AMOUNT = S.TOTAL_AMOUNT,
    T.AVERAGE_AMOUNT = S.AVERAGE_AMOUNT,
    T.LAST_UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_DATE,
    EVENT_TYPE,
    TRANSACTION_COUNT,
    TOTAL_AMOUNT,
    AVERAGE_AMOUNT,
    LAST_UPDATED_AT
)
VALUES (
    S.TRANSACTION_DATE,
    S.EVENT_TYPE,
    S.TRANSACTION_COUNT,
    S.TOTAL_AMOUNT,
    S.AVERAGE_AMOUNT,
    CURRENT_TIMESTAMP()
);
