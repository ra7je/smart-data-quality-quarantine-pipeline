
CREATE OR REPLACE VIEW SMART_DATA_QUALITY_DB.AUDIT.DATA_QUALITY_METRICS AS

WITH QUARANTINE_METRICS AS (
    SELECT
        RUN_ID,
        COUNT(*) AS TOTAL_QUARANTINED,
        COUNT_IF(STATUS = 'PENDING') AS PENDING_RECORDS,
        COUNT_IF(STATUS = 'REPLAYED') AS REPLAYED_RECORDS
    FROM SMART_DATA_QUALITY_DB.SILVER.QUARANTINE_RECORDS
    GROUP BY RUN_ID
)

SELECT
    P.RUN_ID,
    P.SOURCE_FILE,
    P.START_TIME,
    P.END_TIME,
    P.INPUT_COUNT,
    P.VALID_COUNT,
    P.REJECTED_COUNT,
    P.DUPLICATE_COUNT,
    P.RUN_STATUS,
    P.EXECUTION_SECONDS,

    COALESCE(Q.TOTAL_QUARANTINED, 0)
        AS TOTAL_QUARANTINED,

    COALESCE(Q.PENDING_RECORDS, 0)
        AS PENDING_RECORDS,

    COALESCE(Q.REPLAYED_RECORDS, 0)
        AS REPLAYED_RECORDS,

    CASE
        WHEN P.INPUT_COUNT = 0 THEN 0
        ELSE ROUND(
            P.VALID_COUNT * 100.0 / P.INPUT_COUNT,
            2
        )
    END AS DATA_QUALITY_SCORE

FROM SMART_DATA_QUALITY_DB.AUDIT.PIPELINE_RUNS P

LEFT JOIN QUARANTINE_METRICS Q
    ON P.RUN_ID = Q.RUN_ID;
