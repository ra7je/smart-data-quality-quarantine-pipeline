
CREATE TABLE IF NOT EXISTS SMART_DATA_QUALITY_DB.GOLD.FACT_TRANSACTIONS AS
SELECT
    EVENT_ID,
    CUSTOMER_ID,
    EVENT_TYPE,
    AMOUNT,
    EVENT_TIMESTAMP,
    SOURCE_FILE,
    RUN_ID,
    CURRENT_TIMESTAMP() AS GOLD_LOADED_AT
FROM SMART_DATA_QUALITY_DB.SILVER.VALID_TRANSACTIONS
WHERE 1 = 0;


MERGE INTO SMART_DATA_QUALITY_DB.GOLD.FACT_TRANSACTIONS T
USING (
    SELECT
        EVENT_ID,
        CUSTOMER_ID,
        EVENT_TYPE,
        AMOUNT,
        EVENT_TIMESTAMP,
        SOURCE_FILE,
        RUN_ID
    FROM SMART_DATA_QUALITY_DB.SILVER.VALID_TRANSACTIONS
) S
ON T.EVENT_ID = S.EVENT_ID

WHEN NOT MATCHED THEN
INSERT (
    EVENT_ID,
    CUSTOMER_ID,
    EVENT_TYPE,
    AMOUNT,
    EVENT_TIMESTAMP,
    SOURCE_FILE,
    RUN_ID,
    GOLD_LOADED_AT
)
VALUES (
    S.EVENT_ID,
    S.CUSTOMER_ID,
    S.EVENT_TYPE,
    S.AMOUNT,
    S.EVENT_TIMESTAMP,
    S.SOURCE_FILE,
    S.RUN_ID,
    CURRENT_TIMESTAMP()
);
