
-- =====================================================
-- DATA QUALITY PIPELINE RECONCILIATION
-- =====================================================

WITH COUNTS AS (

    SELECT
        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.BRONZE.RAW_TRANSACTIONS)
            AS BRONZE_COUNT,

        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.SILVER.VALID_TRANSACTIONS)
            AS SILVER_COUNT,

        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.SILVER.QUARANTINE_RECORDS
         WHERE STATUS = 'PENDING')
            AS PENDING_QUARANTINE_COUNT,

        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.SILVER.QUARANTINE_RECORDS
         WHERE STATUS = 'REPLAYED')
            AS REPLAYED_COUNT,

        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.GOLD.FACT_TRANSACTIONS)
            AS GOLD_COUNT,

        (SELECT COUNT(*)
         FROM SMART_DATA_QUALITY_DB.AUDIT.REPLAY_HISTORY
         WHERE REPLAY_STATUS = 'SUCCESS')
            AS SUCCESSFUL_REPLAY_COUNT

)

SELECT
    BRONZE_COUNT,
    SILVER_COUNT,
    PENDING_QUARANTINE_COUNT,
    REPLAYED_COUNT,
    GOLD_COUNT,
    SUCCESSFUL_REPLAY_COUNT,

    SILVER_COUNT + PENDING_QUARANTINE_COUNT
        AS RECONCILED_COUNT,

    CASE
        WHEN BRONZE_COUNT =
             SILVER_COUNT + PENDING_QUARANTINE_COUNT
        THEN 'PASS'
        ELSE 'CHECK REQUIRED'
    END AS RECONCILIATION_STATUS,

    CASE
        WHEN SILVER_COUNT = GOLD_COUNT
        THEN 'PASS'
        ELSE 'GOLD REFRESH REQUIRED'
    END AS GOLD_RECONCILIATION_STATUS

FROM COUNTS;
